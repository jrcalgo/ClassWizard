"""Convert syllabus concept-map extractions into valid triples for Postgres.

Input (any directory tree; files are found recursively):
    *_triples.csv   course,subject,subject_type,predicate,object,object_type,
                    order_evidence,flags,source_file
    *_concepts.csv  course,type,term,as_in_text,occurrences,status,
                    extracted_as,source_file

Rows are grouped by their ``course`` column, not by file name, so this works
both for a folder per course (<COURSE>/<COURSE>_triples.csv, _concepts.csv)
and for a release that ships one combined triples CSV and one concepts CSV.

Output (same 13 columns that embed_triples.py and the syllabus_triples table use):
    data/uncc-courses/syllabi/valid_triples_for_postgres.csv
Review files written next to it:
    rejected_triples.csv   every dropped row and the reason it was dropped
    pipeline_report.json   counts per stage, predicate, type and reject reason

Two kinds of rows are produced:
    1. Concept-to-concept relations from *_triples.csv
       (prerequisite_for, part_of, is_subclass_of, used_for).
    2. Course-to-concept ``covers`` rows from *_concepts.csv, one per verified
       or inferred concept, so "which course teaches X" questions can be retrieved even
       for concepts that have no relation in the concept map.

Concepts marked "inferred" (generated by the extractor rather than found in
the syllabus) are kept at lower confidence; see the INFERRED_* constants.

Embeddings are not made here: the backend loader embeds the CSV's rows into
Postgres on first start (backend/storage/database/postgres.py).

Run from the repo root, pointing --input at the extraction folder:
    python -m syllabi_pipeline --input path/to/syllabus_extractions
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import os
import re
import sys
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = REPO_ROOT / "data" / "uncc-courses" / "syllabi" / "valid_triples_for_postgres.csv"
DEFAULT_CATALOG = REPO_ROOT / "data" / "catalog_out"  # every courses_flat.csv below it

OUTPUT_COLUMNS = [
    "triple_id", "subject", "subject_type", "subject_canonical_id",
    "predicate", "object", "object_type", "object_canonical_id",
    "confidence", "evidence", "filename", "page_num", "section_heading",
]

# ---------------------------------------------------------------------------
# Vocabulary mapping: concept-map labels -> the labels already in syllabus_triples
# ---------------------------------------------------------------------------

# Direction is kept as-is: "A PREREQUISITE_OF B" becomes "A prerequisite_for B".
PREDICATE_MAP = {
    "PREREQUISITE_OF": "prerequisite_for",
    "PART_OF": "part_of",
    "SUBTYPE_OF": "is_subclass_of",
    "USED_FOR": "used_for",
}

TYPE_MAP = {
    "concept": "Concept",
    "topic": "Topic",
    "method": "Method",
    "tool": "Technology",  # existing rows call software/tools "Technology"
    "measure": "Measure",
    "work": "Work",
}

VERB = {
    "prerequisite_for": "is a prerequisite for",
    "part_of": "is part of",
    "is_subclass_of": "is a kind of",
    "used_for": "is used for",
}

# How the extractor decided the order of A and B in a PREREQUISITE_OF row.
ORDER_PHRASE = {
    "A taught first": "taught earlier in the course",
    "A mentioned first": "introduced earlier in the syllabus",
    "same unit": "taught in the same unit",
    "B mentioned first": "introduced later in the syllabus",
    "B taught first": "taught later in the course",
    "unknown": "",
    "": "",
}

# ---------------------------------------------------------------------------
# Confidence rules. Values must fit numeric(3, 2).
# ---------------------------------------------------------------------------

BASE_CONFIDENCE = {
    "is_subclass_of": 0.90,
    "part_of": 0.85,
    "used_for": 0.85,
}

# PREREQUISITE_OF depends on whether the syllabus order agrees with the arrow.
PREREQ_CONFIDENCE = {
    "A taught first": 0.90,
    "A mentioned first": 0.80,
    "same unit": 0.75,
    "unknown": 0.70,
    "": 0.70,
    "B mentioned first": 0.60,
    "B taught first": 0.50,
}

FLAGGED_CONFIDENCE_CAP = 0.50  # any "... - check" flag from the extractor
DEFAULT_MIN_CONFIDENCE = 0.60  # flagged rows fall below this and go to review


VERIFIED = "verified"
INFERRED = "inferred"
INFERRED_COVERS_CONFIDENCE = 0.60
INFERRED_RELATION_CAP = 0.65
INFERRED_PAIR_CAP = 0.60

COURSE_RE = re.compile(r"^[A-Z]{2,5}_\d{4}[A-Z]?$")
MAX_TERM_LEN = 200


def clean_text(value: str | None) -> str:
    """Collapse whitespace and strip wrapping quotes."""
    text = re.sub(r"\s+", " ", (value or "")).strip()
    if len(text) >= 2 and text[0] == text[-1] and text[0] in "\"'":
        text = text[1:-1].strip()
    return text


def term_key(term: str) -> str:
    return clean_text(term).lower()


def canonical_id(type_label: str, term: str) -> str:
    """Matches the existing ids, e.g. technology_f46237c0 = md5('agentic ai')[:8]."""
    digest = hashlib.md5(term_key(term).encode("utf-8")).hexdigest()[:8]
    return f"{type_label.lower()}_{digest}"


def triple_id(course: str, subject_id: str, predicate: str, object_id: str) -> str:
    raw = f"{course}|{subject_id}|{predicate}|{object_id}"
    return hashlib.md5(raw.encode("utf-8")).hexdigest()[:12]


def course_display(course: str) -> str:
    return course.replace("_", " ")


def relation_confidence(predicate: str, order_evidence: str, flags: str, inferred_ends: int = 0) -> float:
    if predicate == "prerequisite_for":
        conf = PREREQ_CONFIDENCE.get(order_evidence, 0.70)
    else:
        conf = BASE_CONFIDENCE.get(predicate, 0.80)
    if flags:
        conf = min(conf, FLAGGED_CONFIDENCE_CAP)
    if inferred_ends == 1:
        conf = min(conf, INFERRED_RELATION_CAP)
    elif inferred_ends >= 2:
        conf = min(conf, INFERRED_PAIR_CAP)
    return round(conf, 2)


def covers_confidence(occurrences: str, status: str = VERIFIED) -> float:
    if status == INFERRED:
        return INFERRED_COVERS_CONFIDENCE
    try:
        count = int(float(occurrences))
    except (TypeError, ValueError):
        count = 0
    return 0.90 if count >= 2 else 0.80


# ---------------------------------------------------------------------------
# Loading
# ---------------------------------------------------------------------------


@dataclass
class Concept:
    term: str
    type_label: str
    occurrences: str
    status: str  # "verified", "inferred", or anything else (treated as unverified)

    @property
    def inferred(self) -> bool:
        return self.status == INFERRED

    def allowed(self, include_inferred: bool, include_unverified: bool) -> bool:
        if self.status == VERIFIED:
            return True
        if self.status == INFERRED:
            return include_inferred
        return include_unverified


@dataclass
class CourseData:
    concepts: dict[str, Concept] = field(default_factory=dict)
    triples: list[dict] = field(default_factory=list)


def read_csv(path: Path) -> list[dict]:
    with path.open(newline="", encoding="utf-8-sig") as fh:
        return list(csv.DictReader(fh))


def catalog_files(path: Path | None) -> list[Path]:
    """One courses_flat.csv, or every one under a folder (one per catalog level)."""
    if not path:
        return []
    if path.is_file():
        return [path]
    if path.is_dir():
        return sorted(path.rglob("courses_flat.csv"))
    return []


def load_catalog_titles(path: Path | None) -> dict[str, str]:
    """Map 'ACCT 2121' -> 'Principles of Accounting I' from every catalog found."""
    titles = {}
    for csv_path in catalog_files(path):
        for row in read_csv(csv_path):
            code = clean_text(row.get("code"))
            title = clean_text(row.get("title"))
            if code and title:
                titles.setdefault(code, title)
    return titles


def discover(input_dir: Path) -> tuple[list[Path], list[Path]]:
    triples = sorted(p for p in input_dir.rglob("*.csv") if p.stem.lower().endswith("triples"))
    concepts = sorted(p for p in input_dir.rglob("*.csv") if p.stem.lower().endswith("concepts"))
    return triples, concepts


# ---------------------------------------------------------------------------
# Pipeline
# ---------------------------------------------------------------------------


@dataclass
class Result:
    valid: list[dict] = field(default_factory=list)
    rejected: list[dict] = field(default_factory=list)
    reasons: Counter = field(default_factory=Counter)
    warnings: Counter = field(default_factory=Counter)

    def reject(self, row: dict, reason: str, kind: str) -> None:
        self.reasons[reason] += 1
        self.rejected.append({"kind": kind, "reason": reason, **row})


def build(
    triple_files: list[Path],
    concept_files: list[Path],
    titles: dict[str, str],
    min_confidence: float = DEFAULT_MIN_CONFIDENCE,
    include_unverified: bool = False,
    include_covers: bool = True,
    include_inferred: bool = True,
    include_inferred_pairs: bool = False,
) -> tuple[Result, dict]:
    result = Result()
    courses: dict[str, CourseData] = defaultdict(CourseData)
    stats = Counter()

    # 1. Concepts: the per-course vocabulary that triples are checked against.
    for path in concept_files:
        for row in read_csv(path):
            stats["concept_rows_in"] += 1
            course = clean_text(row.get("course"))
            term = clean_text(row.get("term"))
            raw_type = clean_text(row.get("type")).lower()
            if not COURSE_RE.match(course):
                result.reject(row, "bad_course_code", "concept")
                continue
            if not term or len(term) > MAX_TERM_LEN:
                result.reject(row, "bad_term", "concept")
                continue
            if raw_type not in TYPE_MAP:
                result.reject(row, f"unknown_type:{raw_type}", "concept")
                continue
            key = term_key(term)
            if key in courses[course].concepts:
                result.warnings["duplicate_concept_in_course"] += 1
                continue
            courses[course].concepts[key] = Concept(
                term=term,
                type_label=TYPE_MAP[raw_type],
                occurrences=clean_text(row.get("occurrences")),
                status=clean_text(row.get("status")).lower(),
            )
            stats[f"concepts_{courses[course].concepts[key].status or 'blank'}"] += 1

    for path in triple_files:
        for row in read_csv(path):
            stats["triple_rows_in"] += 1
            courses[clean_text(row.get("course"))].triples.append(row)

    seen: set[tuple[str, str]] = set()  # (triple_id, filename) is UNIQUE in Postgres

    def emit(row_out: dict, source_row: dict, kind: str) -> None:
        key = (row_out["triple_id"], row_out["filename"])
        if key in seen:
            result.reject(source_row, "duplicate", kind)
            return
        seen.add(key)
        result.valid.append(row_out)

    for course in sorted(courses):
        data = courses[course]
        filename = f"{course}.pdf"
        label = course_display(course)
        title = titles.get(label)
        course_label = f"{label} ({title})" if title else label
        has_concepts = bool(data.concepts)
        if not has_concepts and data.triples:
            result.warnings["course_without_concepts_file"] += 1

        # 2. Concept-to-concept relations.
        for row in data.triples:
            if not COURSE_RE.match(course):
                result.reject(row, "bad_course_code", "relation")
                continue
            subject = clean_text(row.get("subject"))
            obj = clean_text(row.get("object"))
            raw_pred = clean_text(row.get("predicate")).upper()
            s_type_raw = clean_text(row.get("subject_type")).lower()
            o_type_raw = clean_text(row.get("object_type")).lower()
            order_evidence = clean_text(row.get("order_evidence"))
            flags = clean_text(row.get("flags"))

            if not subject or not obj:
                result.reject(row, "missing_subject_or_object", "relation")
                continue
            if len(subject) > MAX_TERM_LEN or len(obj) > MAX_TERM_LEN:
                result.reject(row, "term_too_long", "relation")
                continue
            if raw_pred not in PREDICATE_MAP:
                result.reject(row, f"unknown_predicate:{raw_pred}", "relation")
                continue
            if s_type_raw not in TYPE_MAP or o_type_raw not in TYPE_MAP:
                result.reject(row, "unknown_type", "relation")
                continue
            if term_key(subject) == term_key(obj):
                result.reject(row, "self_loop", "relation")
                continue

            s_type, o_type = TYPE_MAP[s_type_raw], TYPE_MAP[o_type_raw]
            inferred_terms: list[str] = []
            if has_concepts:
                s_con = data.concepts.get(term_key(subject))
                o_con = data.concepts.get(term_key(obj))
                if not s_con or not o_con:
                    result.reject(row, "endpoint_not_in_concepts", "relation")
                    continue
                ends = (s_con, o_con)
                if any(c.status not in (VERIFIED, INFERRED) for c in ends) and not include_unverified:
                    result.reject(row, "endpoint_unverified", "relation")
                    continue
                inferred_terms = [c.term for c in ends if c.inferred]
                if inferred_terms and not include_inferred:
                    result.reject(row, "endpoint_inferred", "relation")
                    continue
                if len(inferred_terms) == 2 and not include_inferred_pairs:
                    result.reject(row, "both_endpoints_inferred", "relation")
                    continue
                if s_con.type_label != s_type or o_con.type_label != o_type:
                    result.warnings["type_taken_from_concepts_file"] += 1
                    s_type, o_type = s_con.type_label, o_con.type_label

            predicate = PREDICATE_MAP[raw_pred]
            conf = relation_confidence(predicate, order_evidence, flags, len(inferred_terms))
            if conf < min_confidence:
                result.reject(row, "flagged_for_review" if flags else "low_confidence", "relation")
                continue

            s_id, o_id = canonical_id(s_type, subject), canonical_id(o_type, obj)
            evidence = f"In {course_label}, {subject} {VERB[predicate]} {obj}"
            phrase = ORDER_PHRASE.get(order_evidence, "") if predicate == "prerequisite_for" else ""
            evidence += f" ({subject} is {phrase})." if phrase else "."
            if inferred_terms:
                evidence += f" Inferred, not quoted from the syllabus: {'; '.join(inferred_terms)}."
                stats["relations_with_inferred_end"] += 1

            emit(
                {
                    "triple_id": triple_id(course, s_id, predicate, o_id),
                    "subject": subject,
                    "subject_type": s_type,
                    "subject_canonical_id": s_id,
                    "predicate": predicate,
                    "object": obj,
                    "object_type": o_type,
                    "object_canonical_id": o_id,
                    "confidence": f"{conf:.2f}",
                    "evidence": evidence,
                    "filename": filename,
                    "page_num": "",
                    "section_heading": "",
                },
                row,
                "relation",
            )

        # 3. Course-to-concept "covers" rows.
        if include_covers and COURSE_RE.match(course):
            c_id = canonical_id("Course", label)
            for concept in data.concepts.values():
                src = {"course": course, "term": concept.term, "type": concept.type_label}
                if not concept.allowed(include_inferred, include_unverified):
                    reason = "concept_inferred" if concept.inferred else "concept_unverified"
                    result.reject(src, reason, "covers")
                    continue
                o_id = canonical_id(concept.type_label, concept.term)
                evidence = f"{course_label} covers the {concept.type_label.lower()} {concept.term}"
                if concept.inferred:
                    evidence += " (inferred from the syllabus, not quoted from it)"
                    stats["covers_inferred"] += 1
                emit(
                    {
                        "triple_id": triple_id(course, c_id, "covers", o_id),
                        "subject": label,
                        "subject_type": "Course",
                        "subject_canonical_id": c_id,
                        "predicate": "covers",
                        "object": concept.term,
                        "object_type": concept.type_label,
                        "object_canonical_id": o_id,
                        "confidence": f"{covers_confidence(concept.occurrences, concept.status):.2f}",
                        "evidence": evidence + ".",
                        "filename": filename,
                        "page_num": "",
                        "section_heading": "",
                    },
                    src,
                    "covers",
                )

    result.valid.sort(key=lambda r: (r["filename"], r["predicate"], r["subject"].lower(), r["object"].lower()))
    stats["courses"] = sum(1 for c in courses if COURSE_RE.match(c))
    stats["courses_with_catalog_title"] = sum(1 for c in courses if course_display(c) in titles)
    return result, dict(stats)


# ---------------------------------------------------------------------------
# Output
# ---------------------------------------------------------------------------


def write_csv(path: Path, rows: list[dict], columns: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    with tmp.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=columns, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)
    os.replace(tmp, path)


def write_outputs(result: Result, stats: dict, output: Path, input_dir: Path) -> Path:
    write_csv(output, result.valid, OUTPUT_COLUMNS)

    rejected_path = output.parent / "rejected_triples.csv"
    reject_cols = ["kind", "reason"]
    for row in result.rejected:
        for key in row:
            if key not in reject_cols:
                reject_cols.append(key)
    write_csv(rejected_path, result.rejected, reject_cols)

    report = {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "input_dir": display_path(input_dir),
        "output": display_path(output),
        **stats,
        "valid_rows": len(result.valid),
        "valid_by_predicate": dict(Counter(r["predicate"] for r in result.valid).most_common()),
        "valid_by_object_type": dict(Counter(r["object_type"] for r in result.valid).most_common()),
        "rejected_rows": len(result.rejected),
        "rejected_by_reason": dict(result.reasons.most_common()),
        "warnings": dict(result.warnings.most_common()),
    }
    report_path = output.parent / "pipeline_report.json"
    report_path.write_text(json.dumps(report, indent=2), encoding="utf-8")
    return report_path


def display_path(path: Path) -> str:
    """Repo-relative when possible, so reports do not carry a home folder."""
    try:
        return path.resolve().relative_to(REPO_ROOT).as_posix()
    except ValueError:
        return path.name


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--input", required=True, type=Path,
                   help="folder containing *_triples.csv and *_concepts.csv (searched recursively)")
    p.add_argument("--output", type=Path, default=DEFAULT_OUTPUT,
                   help=f"output CSV (default: {DEFAULT_OUTPUT.relative_to(REPO_ROOT)})")
    p.add_argument("--catalog", type=Path, default=DEFAULT_CATALOG,
                   help="courses_flat.csv, or a folder searched for them (one per catalog level), "
                        "used to add course titles to evidence text (optional)")
    p.add_argument("--min-confidence", type=float, default=DEFAULT_MIN_CONFIDENCE,
                   help="relations below this go to rejected_triples.csv (0 keeps flagged rows)")
    p.add_argument("--no-inferred", action="store_true",
                   help="drop concepts with status 'inferred' entirely")
    p.add_argument("--include-inferred-pairs", action="store_true",
                   help="keep relations whose two ends are both inferred (capped at 0.60)")
    p.add_argument("--include-unverified", action="store_true",
                   help="keep concepts whose status is neither 'verified' nor 'inferred'")
    p.add_argument("--no-covers", action="store_true",
                   help="skip the course-covers-concept rows")
    return p.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    input_dir = args.input.resolve()
    if not input_dir.is_dir():
        print(f"Input folder not found: {input_dir}", file=sys.stderr)
        return 2

    triple_files, concept_files = discover(input_dir)
    if not triple_files and not concept_files:
        print(f"No *_triples.csv or *_concepts.csv files under {input_dir}", file=sys.stderr)
        return 2
    print(f"Found {len(triple_files)} triples files and {len(concept_files)} concepts files.")

    titles = load_catalog_titles(args.catalog)
    if not titles:
        print("Catalog titles not found; evidence text will use course codes only.")

    result, stats = build(
        triple_files,
        concept_files,
        titles,
        min_confidence=args.min_confidence,
        include_unverified=args.include_unverified,
        include_covers=not args.no_covers,
        include_inferred=not args.no_inferred,
        include_inferred_pairs=args.include_inferred_pairs,
    )
    report_path = write_outputs(result, stats, args.output.resolve(), input_dir)

    by_pred = Counter(r["predicate"] for r in result.valid)
    print(f"Courses: {stats.get('courses', 0)}  "
          f"(with catalog title: {stats.get('courses_with_catalog_title', 0)})")
    print(f"Valid rows: {len(result.valid)}  {dict(by_pred.most_common())}")
    print(f"Rejected rows: {len(result.rejected)}  {dict(result.reasons.most_common())}")
    if result.warnings:
        print(f"Warnings: {dict(result.warnings)}")
    print(f"Wrote {args.output}")
    print(f"Report: {report_path}")
    print("The backend embeds new rows on its next start; bump SYLLABI_RELEASE in "
          "backend/storage/database/postgres.py so it reloads them.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
